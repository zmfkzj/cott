from cott_runtime import CottList, Nothing, Some

from real.harlequin.keymap_types import KeyBinding, KeyMap


def _binding(row: str) -> KeyBinding:
    keys, action, display = row.split("|")
    if display == "-":
        return KeyBinding(keys=keys, action=action, key_display=Nothing())
    return KeyBinding(keys=keys, action=action, key_display=Some(value=display))


